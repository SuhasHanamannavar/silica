import json
from datetime import datetime
from typing import Dict, Any, List

class DocumentAssembler:
    """
    Assembles all agent outputs into human-readable Markdown documents.
    Also generates the human review checklist and spec freeze package.
    """
    
    def __init__(self, llm_backend):
        self.llm = llm_backend
    
    def run(self, all_outputs: Dict, **kwargs) -> Dict:
        """Assemble complete specification documents."""
        market = all_outputs.get("market_analysis", {})
        func = all_outputs.get("functional_spec", {})
        nfr = all_outputs.get("non_functional_spec", {})
        tradeoffs = all_outputs.get("tradeoff_analysis", {})
        roofline = all_outputs.get("roofline_analysis", {})
        block_diag = all_outputs.get("block_diagram", {})
        interfaces = all_outputs.get("interface_spec", {})
        risks = all_outputs.get("risk_register", {})
        die_cost = all_outputs.get("die_cost_model", {})
        
        documents = {
            "00_MARKET_REQUIREMENTS.md": self._gen_mrd(market),
            "01_FUNCTIONAL_SPECIFICATION.md": self._gen_func_spec(func),
            "02_NON_FUNCTIONAL_SPECIFICATION.md": self._gen_nfr_spec(nfr),
            "03_ARCHITECTURAL_TRADEOFFS.md": self._gen_tradeoffs(tradeoffs),
            "04_ROOFLINE_ANALYSIS.md": self._gen_roofline(roofline),
            "05_BLOCK_DIAGRAM_ARCHITECTURE.md": self._gen_block_diag(block_diag),
            "06_INTERFACE_SPECIFICATION.md": self._gen_interfaces(interfaces),
            "07_RISK_REGISTER.md": self._gen_risks(risks),
            "08_DIE_COST_MODEL.md": self._gen_cost(die_cost),
            "09_HUMAN_REVIEW_CHECKLIST.md": self._gen_checklist(all_outputs),
            "10_SPECIFICATION_SUMMARY.md": self._gen_summary(all_outputs),
        }
        
        # Full spec package as single document
        full_spec = "# COMPLETE GPU ARCHITECTURE SPECIFICATION\n\n"
        full_spec += "**Generated by Silica Product Architect**  \n"
        full_spec += f"**Date:** {self._timestamp()}  \n"
        full_spec += "**Status:** DRAFT FOR HUMAN REVIEW\n\n"
        full_spec += "---\n\n"
        
        for name, content in documents.items():
            full_spec += f"\n\n<!-- FILE: {name} -->\n\n{content}\n\n"
        
        documents["FULL_SPECIFICATION_PACKAGE.md"] = full_spec
        
        return {
            "documents": documents,
            "review_checklist": self._get_checklist_items(),
            "spec_freeze_criteria": self._get_freeze_criteria(),
            "downstream_handoff": self._generate_handoff(all_outputs),
        }
    
    def _gen_func_spec(self, spec: Dict) -> str:
        """Generate Markdown functional spec."""
        lines = ["# FUNCTIONAL SPECIFICATION", ""]
        
        # Compute Architecture
        lines.append("## 1. Compute Architecture")
        lines.append("")
        lines.append("### 1.1 Precision Formats")
        lines.append("")
        lines.append("| Format | Peak Throughput | Enabled |")
        lines.append("|--------|-----------------|---------|")
        for fmt in spec.get("compute_architecture", {}).get("precision_formats", []):
            peak = fmt.get("peak_tflops", fmt.get("peak_tops", "N/A"))
            unit = "TFLOPS" if "tflops" in str(fmt).lower() else "TOPS"
            lines.append(f"| {fmt.get('format', '?')} | {peak} {unit} | {'✓' if fmt.get('enabled', True) else '✗'} |")
        
        lines.append("")
        lines.append("### 1.2 SM Architecture")
        lines.append("")
        sm = spec.get("compute_architecture", {}).get("sm_architecture", {})
        for key, val in sm.items():
            lines.append(f"- **{key.replace('_', ' ').title()}**: {val}")
        
        # Memory Hierarchy
        lines.append("")
        lines.append("## 2. Memory Hierarchy")
        lines.append("")
        hbm = spec.get("memory_hierarchy", {}).get("hbm_subsystem", {})
        lines.append("### 2.1 HBM Subsystem")
        lines.append("")
        for key, val in hbm.items():
            lines.append(f"- **{key.replace('_', ' ').title()}**: {val}")
        
        l2 = spec.get("memory_hierarchy", {}).get("l2_cache", {})
        lines.append("")
        lines.append("### 2.2 L2 Cache")
        lines.append("")
        for key, val in l2.items():
            lines.append(f"- **{key.replace('_', ' ').title()}**: {val}")
        
        # Interconnect
        lines.append("")
        lines.append("## 3. Interconnect")
        lines.append("")
        ic = spec.get("interconnect", {})
        idx = 1
        for iface_name, iface_spec in ic.items():
            lines.append(f"### 3.{idx} {iface_name.replace('_', ' ').title()}")
            lines.append("")
            if isinstance(iface_spec, dict):
                for key, val in iface_spec.items():
                    lines.append(f"- **{key.replace('_', ' ').title()}**: {val}")
            lines.append("")
            idx += 1
        
        return "\n".join(lines)
    
    def _gen_nfr_spec(self, spec: Dict) -> str:
        """Generate Markdown non-functional spec."""
        lines = ["# NON-FUNCTIONAL SPECIFICATION", ""]
        
        power = spec.get("power_budget", {})
        lines.append("## 1. Power Budget")
        lines.append("")
        lines.append(f"- **Total TDP**: {power.get('total_tdp_watts', '?')} W")
        lines.append("")
        lines.append("### 1.1 Power Allocation")
        lines.append("")
        lines.append("| Subsystem | % | Watts |")
        lines.append("|-----------|---|-------|")
        for name, alloc in power.get("allocation", {}).items():
            lines.append(f"| {name.replace('_', ' ').title()} | {alloc.get('percent', '?')}% | {alloc.get('watts', '?')} W |")
        
        area = spec.get("area_budget", {})
        lines.append("")
        lines.append("## 2. Area Budget")
        lines.append("")
        lines.append(f"- **Total Die Area**: {area.get('total_die_area_mm2', '?')} mm²")
        lines.append(f"- **Reticle Limit Check**: {area.get('reticle_limit_check', '?')}")
        lines.append(f"- **Chiplet Required**: {'Yes' if area.get('chiplet_required', False) else 'No'}")
        lines.append("")
        lines.append("### 2.1 Area Allocation")
        lines.append("")
        lines.append("| Subsystem | % | mm² |")
        lines.append("|-----------|---|-----|")
        for name, alloc in area.get("allocation", {}).items():
            lines.append(f"| {name.replace('_', ' ').title()} | {alloc.get('percent', '?')}% | {alloc.get('mm2', '?')} mm² |")
        
        thermal = spec.get("thermal_specification", {})
        lines.append("")
        lines.append("## 3. Thermal Specification")
        lines.append("")
        for key, val in thermal.items():
            lines.append(f"- **{key.replace('_', ' ').title()}**: {val}")
        
        cost = spec.get("cost_targets", {})
        lines.append("")
        lines.append("## 4. Cost Targets")
        lines.append("")
        for key, val in cost.items():
            lines.append(f"- **{key.replace('_', ' ').title()}**: {val}")
        
        return "\n".join(lines)
    
    def _gen_roofline(self, roofline: Dict) -> str:
        lines = ["# ROOFLINE ANALYSIS", ""]
        lines.append("## Key Parameters")
        lines.append("")
        pc = roofline.get("peak_compute", {})
        lines.append(f"- **Peak BF16**: {pc.get('bf16_tflops', '?')} TFLOPS")
        lines.append(f"- **Peak FP8**: {pc.get('fp8_tflops', '?')} TFLOPS")
        lines.append(f"- **HBM Bandwidth**: {roofline.get('memory_bandwidth_tbs', '?')} TB/s")
        rp = roofline.get("ridge_points", {})
        lines.append(f"- **Ridge Point (BF16)**: {rp.get('bf16_flops_per_byte', '?')} FLOPs/byte")
        lines.append(f"- **Ridge Point (FP8)**: {rp.get('fp8_flops_per_byte', '?')} FLOPs/byte")
        lines.append("")
        
        lines.append("## Workload Analysis")
        lines.append("")
        lines.append("| Workload | AI (FLOPs/B) | BF16 Bound | BF16 Util % | FP8 Bound | FP8 Util % |")
        lines.append("|----------|-------------|------------|-------------|-----------|------------|")
        for wl in roofline.get("workload_analysis", []):
            b = wl.get("bf16", {})
            f = wl.get("fp8", {})
            lines.append(f"| {wl.get('workload', '?')} | {wl.get('arithmetic_intensity_flops_per_byte', '?')} | {b.get('bound_type', '?')} | {b.get('peak_utilization_percent', '?')}% | {f.get('bound_type', '?')} | {f.get('peak_utilization_percent', '?')}% |")
        
        lines.append("")
        lines.append("## Interpretation")
        lines.append("")
        lines.append(roofline.get("interpretation", "N/A"))
        lines.append("")
        lines.append("## ASCII Roofline Plot")
        lines.append("")
        lines.append("```")
        lines.append(roofline.get("ascii_roofline", ""))
        lines.append("```")
        
        return "\n".join(lines)
    
    def _gen_tradeoffs(self, tradeoffs: Dict) -> str:
        lines = ["# ARCHITECTURAL TRADEOFF ANALYSIS", ""]
        
        if isinstance(tradeoffs, dict) and "decisions_summary" in tradeoffs:
            for d in tradeoffs["decisions_summary"]:
                lines.append(f"## {d.get('decision_id', 'Decision').replace('_', ' ').title()}")
                lines.append("")
                lines.append(f"**Recommendation**: {d.get('recommendation', '?')}")
                lines.append("")
                lines.append(f"**Rationale**: {d.get('rationale', '?')}")
                lines.append("")
                for opt in d.get("options_analyzed", []):
                    lines.append(f"### Option: {opt.get('option_name', '?')}")
                    scores = opt.get("scores", {})
                    score_str = " | ".join(f"{k}: {v}" for k, v in scores.items())
                    lines.append(f"- **Scores**: {score_str}")
                    lines.append(f"- **Pros**: {', '.join(opt.get('pros', []))}")
                    lines.append(f"- **Cons**: {', '.join(opt.get('cons', []))}")
                lines.append("")
        elif isinstance(tradeoffs, dict):
            for key, val in tradeoffs.items():
                if key.startswith("_"):
                    continue
                lines.append(f"## {key.replace('_', ' ').title()}")
                lines.append("")
                lines.append(f"```json\n{json.dumps(val, indent=2)[:2000]}\n```")
                lines.append("")
        
        return "\n".join(lines)
    
    def _gen_block_diag(self, diag: Dict) -> str:
        lines = ["# BLOCK DIAGRAM ARCHITECTURE", ""]
        
        lines.append("## Chiplet Strategy")
        lines.append("")
        cs = diag.get("chiplet_strategy", {})
        for k, v in cs.items():
            lines.append(f"- **{k.replace('_', ' ').title()}**: {v}")
        
        lines.append("")
        lines.append("## Per-Die Structure")
        lines.append("")
        pds = diag.get("per_die_structure", {})
        for k, v in pds.items():
            lines.append(f"- **{k.replace('_', ' ').title()}**: {v}")
        
        lines.append("")
        lines.append("## ASCII Floorplan")
        lines.append("")
        lines.append("```")
        lines.append(diag.get("ascii_diagram", ""))
        lines.append("```")
        
        lines.append("")
        lines.append("## Mermaid Diagram")
        lines.append("")
        lines.append("```mermaid")
        lines.append(diag.get("mermaid_diagram", ""))
        lines.append("```")
        
        lines.append("")
        lines.append("## Floorplan Notes")
        lines.append("")
        for note in diag.get("floorplan_notes", []):
            lines.append(f"- {note}")
        
        return "\n".join(lines)
    
    def _gen_interfaces(self, ifaces: Dict) -> str:
        lines = ["# INTERFACE SPECIFICATION", ""]
        ext = ifaces.get("external_interfaces", {})
        for name, spec in ext.items():
            lines.append(f"## {name.upper()}")
            lines.append("")
            if isinstance(spec, dict):
                for k, v in spec.items():
                    if isinstance(v, (dict, list)):
                        lines.append(f"- **{k.replace('_', ' ').title()}**:")
                        lines.append(f"  ```json\n  {json.dumps(v, indent=2)[:1000]}\n  ```")
                    else:
                        lines.append(f"- **{k.replace('_', ' ').title()}**: {v}")
            lines.append("")
        return "\n".join(lines)
    
    def _gen_risks(self, risks: Dict) -> str:
        lines = ["# RISK REGISTER", ""]
        lines.append(f"**Summary**: {risks.get('summary', 'N/A')}")
        lines.append("")
        lines.append(f"- **High risks (≥15)**: {risks.get('high_risk_count', '?')}")
        lines.append(f"- **Medium risks (10-14)**: {risks.get('medium_risk_count', '?')}")
        lines.append(f"- **Low risks (<10)**: {risks.get('low_risk_count', '?')}")
        lines.append("")
        lines.append("## Risk Details")
        lines.append("")
        lines.append("| ID | Description | Category | L | I | Score | Mitigation | Owner |")
        lines.append("|----|-------------|----------|---|---|-------|------------|-------|")
        for r in risks.get("risks", [])[:20]:
            if not isinstance(r, dict):
                continue
            lines.append(f"| {r.get('risk_id', '?')} | {str(r.get('description', '?'))[:60]} | {r.get('category', '?')} | {r.get('likelihood', '?')} | {r.get('impact', '?')} | {r.get('risk_score', '?')} | {str(r.get('mitigation', '?'))[:50]} | {r.get('owner', '?')} |")
        
        return "\n".join(lines)
    
    def _gen_cost(self, cost: Dict) -> str:
        lines = ["# DIE COST MODEL", ""]
        for k, v in cost.items():
            if k.startswith("_"):
                continue
            lines.append(f"- **{k.replace('_', ' ').title()}**: {v}")
        return "\n".join(lines)
    
    def _gen_mrd(self, market: Dict) -> str:
        lines = ["# MARKET REQUIREMENTS DOCUMENT", ""]
        lines.append("```json")
        lines.append(json.dumps(market, indent=2)[:5000])
        lines.append("```")
        return "\n".join(lines)
    
    def _gen_checklist(self, all_outputs: Dict) -> str:
        lines = ["# HUMAN REVIEW CHECKLIST", ""]
        lines.append("## Architecture Review")
        lines.append("")
        for item in self._get_checklist_items():
            lines.append(f"- [ ] **{item['area']}**: {item['question']}")
            lines.append(f"  - *Evidence*: {item['evidence']}")
        lines.append("")
        lines.append("## Sign-off")
        lines.append("")
        lines.append("| Role | Name | Signature | Date |")
        lines.append("|------|------|-----------|------|")
        lines.append("| Product Architect | | | |")
        lines.append("| Chip Architect | | | |")
        lines.append("| RTL Design Lead | | | |")
        lines.append("| Verification Lead | | | |")
        lines.append("| Physical Design Lead | | | |")
        lines.append("| Software Lead | | | |")
        lines.append("| Program Manager | | | |")
        return "\n".join(lines)
    
    def _gen_summary(self, all_outputs: Dict) -> str:
        func = all_outputs.get("functional_spec", {})
        nfr = all_outputs.get("non_functional_spec", {})
        sm = func.get("compute_architecture", {}).get("sm_architecture", {})
        hbm = func.get("memory_hierarchy", {}).get("hbm_subsystem", {})
        power = nfr.get("power_budget", {})
        area = nfr.get("area_budget", {})
        
        lines = ["# SPECIFICATION SUMMARY", ""]
        lines.append("## At a Glance")
        lines.append("")
        lines.append(f"- **SM Count**: {sm.get('total_sm_count', '?')}")
        lines.append(f"- **Boost Clock**: {sm.get('boost_clock_mhz', '?')} MHz")
        lines.append(f"- **HBM**: {hbm.get('total_capacity_gb', '?')} GB at {hbm.get('total_bandwidth_tbs', '?')} TB/s")
        lines.append(f"- **TDP**: {power.get('total_tdp_watts', '?')} W")
        lines.append(f"- **Die Area**: {area.get('total_die_area_mm2', '?')} mm²")
        lines.append(f"- **Chiplet**: {'Yes' if area.get('chiplet_required', False) else 'No'}")
        lines.append("")
        lines.append("## Status")
        lines.append("")
        lines.append("**DRAFT FOR HUMAN REVIEW** — This specification has been generated by Silica AI.")
        lines.append("All numbers are preliminary and require expert review before spec freeze.")
        return "\n".join(lines)
    
    def _generate_handoff(self, all_outputs: Dict) -> Dict:
        """Generate structured handoff to downstream agents."""
        func = all_outputs.get("functional_spec", {})
        nfr = all_outputs.get("non_functional_spec", {})
        
        return {
            "for_rtl_design": {
                "sm_count": func.get("compute_architecture", {}).get("sm_architecture", {}).get("total_sm_count", 144),
                "clock_mhz": func.get("compute_architecture", {}).get("sm_architecture", {}).get("boost_clock_mhz", 2250),
                "interfaces": func.get("interconnect", {}),
                "instruction_set": func.get("compute_architecture", {}).get("instruction_set", {}),
            },
            "for_verification": {
                "functional_requirements": func,
                "performance_targets": nfr.get("performance_constraints", {}),
                "reliability_requirements": nfr.get("reliability_availability", {}),
            },
            "for_physical_design": {
                "die_area_mm2": nfr.get("area_budget", {}).get("total_die_area_mm2", 1180),
                "power_budget_w": nfr.get("power_budget", {}).get("total_tdp_watts", 1000),
                "clock_frequencies": nfr.get("performance_constraints", {}).get("clock_frequencies", {}),
                "block_diagram": all_outputs.get("block_diagram", {}),
            },
            "spec_freeze_status": "DRAFT — AWAITING HUMAN SIGN-OFF",
        }
    
